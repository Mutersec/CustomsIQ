"""Tests for invoice field extraction and the upload endpoint.

Most of these drive `extract_fields` with plain text — it is pure, so a PDF is
only needed for the tests that are actually about PDF reading. The fixtures are
generated by tests/fixtures/make_invoice_pdfs.py and committed alongside it.
"""

